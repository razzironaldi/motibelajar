"""Static migration audit; runtime PostgreSQL checks remain mandatory."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
MIGRATION_DIR = ROOT / "supabase" / "migrations"
REPORT = ROOT / "docs" / "static-policy-inventory.md"
SQL = "\n".join(p.read_text(encoding="utf-8") for p in sorted(MIGRATION_DIR.glob("*.sql")))

tables = sorted(set(re.findall(r"create\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-z_][a-z0-9_]*)", SQL, re.I)))
rls_explicit = set(re.findall(r"alter\s+table\s+public\.([a-z_][a-z0-9_]*)\s+enable\s+row\s+level\s+security", SQL, re.I))
force_explicit = set(re.findall(r"alter\s+table\s+public\.([a-z_][a-z0-9_]*)\s+force\s+row\s+level\s+security", SQL, re.I))
dynamic_rls = "for t in select tablename from pg_catalog.pg_tables" in SQL
policy_re = re.compile(r"create\s+policy\s+(?P<name>[a-z_][a-z0-9_]*)\s+on\s+public\.(?P<table>[a-z_][a-z0-9_]*)(?:\s+as\s+(?P<kind>permissive|restrictive))?\s+for\s+(?P<cmd>select|insert|update|delete|all)\s+to\s+(?P<roles>[^\s]+(?:\s*,\s*[^\s]+)*)\s+(?:(?:using\s*\((?P<using>.*?)\))?\s*(?:with\s+check\s*\((?P<check>.*?)\))?)?\s*;", re.I | re.S)
policies = list(policy_re.finditer(SQL))

def clean(value: str | None) -> str:
    return re.sub(r"\s+", " ", value or "<none>").strip()

def table_grants(table: str) -> list[str]:
    pattern = re.compile(r"^\s*grant\s+(.+?)\s+on\s+(?:table\s+)?public\." + re.escape(table) + r"\s+to\s+(.+?)\s*;\s*$", re.I)
    return [f"{clean(match.group(1))} TO {clean(match.group(2))}" for line in SQL.splitlines() if (match := pattern.match(line))]

policy_by_table: dict[str, list[dict[str, str]]] = {table: [] for table in tables}
for match in policies:
    policy_by_table.setdefault(match.group("table"), []).append({key: clean(match.group(key)) for key in ("name", "kind", "cmd", "roles", "using", "check")})

sensitive = {"profiles", "counselor_assignments", "counselor_permissions", "counseling_notes", "counseling_sessions", "file_assets", "file_publications", "assessment_assignments", "assessment_attempts", "assessment_answers", "assessment_result_snapshots", "assessment_scoring_configs", "assessment_answer_keys", "quiz_answer_keys"}
errors: list[str] = []
if not dynamic_rls and set(tables) - rls_explicit:
    errors.append("tables without explicit RLS enablement: " + ", ".join(sorted(set(tables) - rls_explicit)))
index = re.search(r"create\s+unique\s+index\s+one_active_primary_bk_per_student.*", SQL, re.I)
if index and "now()" in index.group(0):
    errors.append("primary assignment index contains now()")
if any(re.search(r"create\s+policy\s+\w+_deny_all\s+on\s+public\.[\w]+\s+(?!as\s+restrictive)", line, re.I) for line in SQL.splitlines()):
    errors.append("deny-all policy is not explicitly restrictive")
for required_sql in ("counseling_notes_session_fk", "public_site_lessons_course_fk", "assessment_attempt_integrity", "assessment_answer_integrity", "file_publication_integrity"):
    if required_sql not in SQL:
        errors.append(f"missing integrity object: {required_sql}")
for helper in ("current_app_role", "is_primary_bk", "is_published_public_asset", "enforce_operational_primary", "validate_assessment_attempt_integrity", "validate_assessment_answer_integrity", "validate_file_publication_integrity"):
    match = re.search(rf"create\s+or\s+replace\s+function\s+public\.{helper}\b.*?(?=\ncreate\s|\ncomment\s|\Z)", SQL, re.I | re.S)
    if not match:
        errors.append(f"missing helper: {helper}")
    else:
        body = match.group(0).lower()
        for required in ("security definer", "set search_path"):
            if required not in body:
                errors.append(f"{helper} lacks {required}")

lines = ["# Static policy inventory", "", "Generated by `scripts/audit_sql.py` from migration text.", "Runtime values require PostgreSQL execution.", "", f"Tables: {len(tables)} | Explicit RLS markers: {len(rls_explicit)} | Dynamic RLS block: {'yes' if dynamic_rls else 'no'}", "", "| Table | RLS | FORCE RLS | Grants | Policies |", "|---|---|---|---|---|"]
for table in tables:
    rls = "YES (dynamic)" if dynamic_rls else ("YES" if table in rls_explicit else "NO")
    force = "YES" if table in force_explicit else "NO (not declared)"
    grants = "<none>" if not table_grants(table) else "<br>".join(table_grants(table))
    rows = policy_by_table.get(table, [])
    policy_text = "<no policy>" if not rows else "<br>".join(f"`{p['name']}` {p['kind']} {p['cmd']} TO {p['roles']}<br>USING `{p['using']}`<br>CHECK `{p['check']}`" for p in rows)
    lines.append(f"| `{table}` | {rls} | {force} | {grants} | {policy_text} |")
lines += ["", "## Intentional policy gaps", ""]
for table in tables:
    if table in sensitive and not policy_by_table.get(table):
        lines.append(f"- `{table}`: no statically parsed policy. Expected default-deny only if runtime RLS is enabled; verify with pgTAP.")
lines += ["", "## Restrictive deny-all", ""]
for table, rows in policy_by_table.items():
    for p in rows:
        if p["kind"].lower() == "restrictive" and p["using"] == "false" and p["check"] == "false":
            lines.append(f"- `{table}` / `{p['name']}`: restrictive deny-all.")
lines += ["", "## Static result", "", "- FAIL: " + "; ".join(errors) if errors else "- PASS: structural guardrails only; runtime SQL/RLS/Storage/Auth remain unverified."]
REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"tables={len(tables)} explicit_rls={len(rls_explicit)} dynamic_rls={dynamic_rls} policies={len(policies)}")
print(f"report={REPORT}")
if errors:
    print("STATIC AUDIT FAIL")
    print("\n".join(f"- {error}" for error in errors))
    sys.exit(1)
print("STATIC AUDIT PASS: structural guardrails only")
